"""Generate TypeScript declarations from the canonical Pydantic analysis schema."""
import json
from pathlib import Path
from backend.app.schemas.analysis import EmailAnalysisResponse

def ts(schema):
    if '$ref' in schema: return schema['$ref'].rsplit('/', 1)[1]
    if 'anyOf' in schema: return ' | '.join(ts(s) for s in schema['anyOf'])
    if 'enum' in schema: return ' | '.join(json.dumps(v) for v in schema['enum'])
    kind = schema.get('type')
    if kind == 'array': return f'Array<{ts(schema.get("items", {}))}>'
    if kind == 'object':
        if 'properties' in schema:
            required = schema.get('required', [])
            return '{\n' + '\n'.join(f'  {json.dumps(k)}{"" if k in required else "?"}: {ts(v)};' for k,v in schema['properties'].items()) + '\n}'
        return f'Record<string, {ts(schema.get("additionalProperties", {})) if isinstance(schema.get("additionalProperties"), dict) else "unknown"}>'
    return {'string':'string', 'integer':'number', 'number':'number', 'boolean':'boolean', 'null':'null'}.get(kind,'unknown')

if __name__ == '__main__':
    schema = EmailAnalysisResponse.model_json_schema(mode="serialization")
    out = '// Generated by scripts/generate_api_types.py; do not edit.\n'
    for name, definition in schema.get('$defs', {}).items(): out += f'export type {name} = {ts(definition)};\n'
    out += f'export type EmailAnalysisResponse = {ts(schema)};\n'
    Path('frontend/src/types/analysis.d.ts').write_text(out)
